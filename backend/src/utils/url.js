/**
 * Подготовка пользовательских ссылок к проверке (сейчас — ссылка на билет).
 *
 * Делает ровно одно: убирает пробелы по краям. Они появляются при вставке из
 * буфера обмена и валидатор из-за них отклоняет совершенно корректный адрес.
 *
 * Протокол НЕ дописывается: адрес пользователь указывает полностью, вместе с
 * http:// или https://. Автодополнение схемы — это догадка за пользователя:
 * для «example.com/x» она обычно верна, но там, где сайт работает только по
 * http, или где в поле оказался вовсе не веб-адрес, приложение открывало бы не
 * то, что человек имел в виду, ничего ему об этом не сказав.
 *
 * Схемы, кроме http/https, отсекает валидатор: по такой ссылке приложение
 * открывает внешний браузер, и произвольная схема (intent:, file:) дала бы
 * организатору мероприятия способ увести пользователя куда угодно.
 */
function normalizeUrl(value) {
    if (value === undefined || value === null) return value;
    return String(value).trim();
}

module.exports = { normalizeUrl };
