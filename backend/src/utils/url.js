/**
 * Нормализация пользовательских ссылок (сейчас — ссылка на покупку билета).
 *
 * Зачем: валидатор требует протокол, а человек вводит адрес так, как привык —
 * «vk.com/club123», «www.timepad.ru/event/1». Такая ссылка не проходила
 * проверку, и сохранить мероприятие было нельзя, хотя адрес корректный.
 * Здесь мы приводим ввод к каноническому виду ДО валидации:
 *   - убираем пробелы по краям (внутри строки пробелов быть не должно);
 *   - дописываем https://, если схема не указана.
 *
 * Схемы, кроме http/https, намеренно НЕ поддерживаем: по такой ссылке
 * приложение открывает внешний браузер, и произвольная схема (intent:, file:)
 * дала бы организатору мероприятия способ увести пользователя куда угодно.
 */
function normalizeUrl(value) {
    if (value === undefined || value === null) return value;
    const trimmed = String(value).trim();
    if (trimmed === '') return '';                       // '' = «очистить»
    // Уже есть схема — оставляем как есть, валидатор отсеет всё, кроме http/https
    if (/^[a-zA-Z][a-zA-Z0-9+.-]*:\/\//.test(trimmed)) return trimmed;
    // Схемы нет — считаем, что это обычный веб-адрес
    return `https://${trimmed}`;
}

module.exports = { normalizeUrl };
