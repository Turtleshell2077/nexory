/**
 * Фильтр нецензурной лексики (RU/EN).
 *
 * ГЛАВНОЕ ПРАВИЛО: проверяем ОТДЕЛЬНЫЕ СЛОВА, а не подстроку во всём тексте.
 *
 * Прежняя версия искала подстроку в тексте целиком, и совершенно безобидные
 * слова блокировались: «команда» содержит «манда», «мандарин» и «мандат» —
 * тоже, английское «account» содержит «cunt». Для приложения про мероприятия
 * слово «команда» встречается едва ли не в каждом описании, так что создать
 * мероприятие часто было просто нельзя.
 *
 * Поэтому список разделён на две части:
 *  - ROOTS         — корни настолько однозначные, что их появление ГДЕ УГОДНО
 *                    внутри слова означает брань («хуй», «пизд», «бляд»);
 *  - WORD_PATTERNS — то, что совпадает только с ЦЕЛЫМ словом, потому что иначе
 *                    цепляет обычную лексику («манда» → «мандарин»).
 *
 * ALLOW — прямые исключения. Нужны на случай, когда в ROOTS попадёт корень,
 * у которого позже обнаружится безобидный «сосед»: добавить слово сюда быстрее
 * и безопаснее, чем переписывать правило.
 */

// Корни, однозначные в любом месте слова
const ROOTS = [
    // Все падежные формы «х*й». Опасности для обычных слов нет: «худой»,
    // «художник», «хуже», «хутор», «хулиган» — везде после «ху» идёт согласная
    'бляд', 'блят', 'хуй', 'хуя', 'хую', 'хуе', 'хуи',
    'пизд', 'еблан', 'ебуч', 'ебан',
    'заеб', 'уеб', 'наеб', 'проеб', 'мудак', 'мудил', 'гандон',
    'пидор', 'пидар', 'ублюдок', 'долбоеб',
    'fuck', 'shit', 'bitch', 'asshole', 'nigger', 'faggot',
];

// Совпадение только с целым словом (с учётом русских окончаний)
const WORD_PATTERNS = [
    /^сук[аиеуой]$/,      // сука, суки, суке… но НЕ «сукно» и не «сук» (ветка)
    /^сучк[аиеуой]$/,
    /^манд[аыеу]$/,       // манда… но НЕ «мандарин», «мандат», «мандраж»
    // ебал, ебут… — только в НАЧАЛЕ слова, поэтому «хлебанул» не задет.
    // Диапазон [а-я] обязателен: \w в JavaScript — это [A-Za-z0-9_], кириллицу
    // он не покрывает, и правило молча совпадало только с «еба»/«ебо»/«ебу»
    /^еб[аоу][а-я]*$/,
    /^cunts?$/,           // но НЕ «account», «discount»
    /^ass(es|hole)?$/,
    /^dick$/,
];

// Заведомо безобидные слова — проверяются раньше всех правил
const ALLOW = new Set([
    'команда', 'команды', 'команде', 'команду', 'командой', 'командир',
    'мандарин', 'мандарины', 'мандарина', 'мандат', 'мандата', 'мандраж',
    'мандолина', 'сукно', 'сукна', 'сук',
    'account', 'accounts', 'discount', 'discounts', 'classic', 'assist',
    'assistant', 'pass', 'password', 'class', 'glass', 'massage',
]);

/**
 * Приводит текст к виду, удобному для сравнения.
 *
 * ВАЖНО: длина строки не меняется — все замены посимвольные. На позициях,
 * найденных в нормализованном тексте, потом маскируется ИСХОДНЫЙ текст, и любое
 * изменение длины сдвинуло бы маску. Раньше здесь схлопывались пробелы
 * (`\s+` → ' '), из-за чего звёздочки в censor() попадали не туда.
 */
function normalize(text) {
    return String(text ?? '')
        .toLowerCase()
        .replace(/ё/g, 'е')
        .replace(/[0@]/g, 'о')
        .replace(/3/g, 'е')
        .replace(/1/g, 'и')
        .replace(/4/g, 'ч');
}

const TOKEN_RE = /[a-zа-я]+/g;

/** Границы бранных слов в ИСХОДНОЙ строке: [{ start, end }]. */
function findProfanity(text) {
    const normalized = normalize(text);
    const hits = [];
    let match;
    TOKEN_RE.lastIndex = 0;
    while ((match = TOKEN_RE.exec(normalized)) !== null) {
        const token = match[0];
        if (ALLOW.has(token)) continue;
        const bad = ROOTS.some(root => token.includes(root)) ||
                    WORD_PATTERNS.some(re => re.test(token));
        if (bad) hits.push({ start: match.index, end: match.index + token.length });
    }
    return hits;
}

/** Есть ли в тексте брань. */
function containsProfanity(text) {
    return findProfanity(text).length > 0;
}

/** Замаскировать бранные слова звёздочками (для сообщений в чатах). */
function censor(text) {
    const original = String(text ?? '');
    const hits = findProfanity(original);
    if (hits.length === 0) return original;

    let out = '';
    let cursor = 0;
    for (const { start, end } of hits) {
        out += original.slice(cursor, start) + '*'.repeat(end - start);
        cursor = end;
    }
    return out + original.slice(cursor);
}

module.exports = { containsProfanity, censor };
