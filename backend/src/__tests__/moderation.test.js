const { containsProfanity, censor } = require('../utils/moderation');

describe('Модерация: обычные тексты не блокируются', () => {
    // Регрессия, из-за которой было заведено это дело: фильтр искал подстроку
    // в тексте целиком, и «команда» блокировалась, потому что содержит «манда».
    // Для приложения про мероприятия это слово встречается постоянно.
    const NORMAL = [
        'Собираем команду на футбол',
        'Нужна команда из 5 человек',
        'Наша команда выиграла',
        'Командный турнир по волейболу',
        'Приходите всей командой',
        'Командировка отменяется',
        'Купил мандарины на всех',
        'Выдали мандат на участие',
        'Мандраж перед стартом',
        'Играем на мандолине',
        'Сукно на бильярдном столе',
        'Спилили сук у дерева',
        'Пробежка в парке у метро',
        'Мастер-класс по рисованию',
        'Художник ведёт мастер-класс',
        'Погода хуже некуда',
        'Едем на хутор в субботу',
        'Худой человек в очках',
        'Please check my account',
        'Discount for students',
        'Enter your password',
        'Classic rock party',
        'Массаж после тренировки',
    ];

    it.each(NORMAL)('пропускает: %s', (text) => {
        expect(containsProfanity(text)).toBe(false);
    });

    it('не трогает текст без брани при маскировке', () => {
        const text = 'Наша команда играет в 18:00';
        expect(censor(text)).toBe(text);
    });
});

describe('Модерация: брань ловится', () => {
    const BAD = [
        'ты сука',
        'сучка драная',
        'какого хуя',
        'иди на хуй',
        'полная хуйня',
        'заебал уже',
        'что за пиздец',
        'ты мудак',
        'ебаный стыд',
        // \w в JS не покрывает кириллицу — правило совпадало только с «еба»
        'ебал',
        'ебут совсем',
        'ебош дальше',
        'hello fuck',
        'this is shit',
        'you bitch',
        'what a cunt',
    ];

    it.each(BAD)('блокирует: %s', (text) => {
        expect(containsProfanity(text)).toBe(true);
    });

    it('ловит замену букв цифрами', () => {
        expect(containsProfanity('иди на ху1')).toBe(true);
        expect(containsProfanity('п1зд3ц')).toBe(true);
    });
});

describe('Модерация: маскировка', () => {
    it('маскирует бранное слово звёздочками', () => {
        const out = censor('ты сука');
        expect(out).not.toContain('сука');
        expect(out).toBe('ты ****');
    });

    it('сохраняет длину и позиции при нескольких пробелах', () => {
        // Раньше normalize() схлопывал пробелы, длина строки менялась,
        // и звёздочки вставлялись не на то место
        const out = censor('привет    сука   пока');
        expect(out).toBe('привет    ****   пока');
    });

    it('маскирует несколько слов подряд', () => {
        const out = censor('сука и мудак');
        expect(out).toBe('**** и *****');
    });

    it('оставляет соседние слова нетронутыми', () => {
        expect(censor('наша команда и сука')).toBe('наша команда и ****');
    });
});
