    /** Подсказки по введённому тексту (до [limit] штук). */
    fun suggest(input: String, limit: Int = 8): List<String> {
        val q = input.trim()
        if (q.isBlank()) return emptyList()
        val lower = q.lowercase()
        return stations
            .filter { it.lowercase().contains(lower) }
            .sortedBy { !it.lowercase().startsWith(lower) } // сперва совпадения с начала
            .take(limit)
    }
