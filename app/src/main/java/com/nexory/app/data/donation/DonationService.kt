package com.nexory.app.data.donation

import android.content.Context

/**
 * Абстракция приёма добровольных пожертвований.
 *
 * Смысл интерфейса — изолировать UI от способа оплаты. Сейчас реализация одна:
 * переход на платёжную страницу банка ([BankLinkDonationService]). Позже, после
 * оформления ИП/самозанятости, появится реализация через агрегатор (ЮKassa/CloudPayments)
 * с выбором банка внутри приложения, СБП-диплинками и подтверждением платежа вебхуком —
 * и её достаточно будет подставить в DI, не меняя экраны.
 *
 * Точки расширения, заложенные заранее:
 *  - [capabilities] позволяет UI узнать, что умеет текущая реализация, и рисовать
 *    соответствующий флоу (список банков / статус платежа) без правок в сервисе;
 *  - [start] принимает необязательную сумму: ссылка банка её игнорирует или
 *    подставляет, а агрегатор будет создавать платёж на точную сумму.
 */
interface DonationService {

    /** Что умеет текущая реализация — UI подстраивается под это. */
    val capabilities: DonationCapabilities

    /**
     * Начать процесс пожертвования.
     * @param amountRubles сумма в рублях, если её выбирает пользователь в приложении.
     *        Для реализации на ссылке банка не используется: сумму вводит пользователь
     *        на стороне банка.
     */
    suspend fun start(context: Context, amountRubles: Int? = null): DonationResult
}

/**
 * Возможности реализации.
 * @param canChooseBankInApp можно ли показать список банков внутри приложения (СБП-диплинки)
 * @param canConfirmPayment  приходит ли подтверждение об оплате (вебхук на бэкенд)
 * @param needsAmountInApp   нужно ли спрашивать сумму в приложении
 */
data class DonationCapabilities(
    val canChooseBankInApp: Boolean,
    val canConfirmPayment:  Boolean,
    val needsAmountInApp:   Boolean,
)

/** Результат попытки начать пожертвование. */
sealed interface DonationResult {
    /**
     * Внешнее приложение/браузер успешно открыто. Подтвердить факт оплаты
     * приложение не может — статус остаётся неизвестным.
     */
    data object OpenedExternally : DonationResult

    /** Не удалось начать: причина в [reason]. */
    data class Failed(val reason: DonationError) : DonationResult
}

/** Причины сбоя — UI показывает по ним понятный текст. */
enum class DonationError {
    /** Нет интернета: открывать платёжную страницу бессмысленно. */
    NO_NETWORK,

    /** Не нашлось приложения, способного открыть ссылку (нет браузера). */
    CANNOT_OPEN,

    /** Реквизиты приёма платежей не настроены в сборке. */
    NOT_CONFIGURED,
}
